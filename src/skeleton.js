//  skeleton.js — هيكل تحميل واحد لكل نوع منطقة (وحدة ESM · W5)
// ═══════════════════════════════════════════════════════════════════════
//
//  ROADMAP §W5-٣: «هيكل عظمي واحد لكل نوع منطقة في كل المسارات لا في أربعة».
//  والقياس عند التنفيذ أظهر ما هو أسوأ من التشتّت:
//
//      خمسون موضعًا تبني هياكل بأربعة عشر ارتفاعًا مختلفًا،
//      **والصنف `.skeleton` نفسه لم يكن مُعرَّفًا في styles.css إطلاقًا.**
//
//  أي أن كل حالة تحميل في المنصّة كانت عنصرًا فارغًا بلا خلفية ولا حركة:
//  يشغل ارتفاعه من الصفحة ولا يُرى. فما بدا «حالة تحميل مطبَّقة في كل مكان»
//  كان فراغًا أبيض في كل مكان — والمستخدم ينتظر أمام شاشة لا تقول شيئًا.
//
//  ولم يكن ليظهر في أي اختبار: الـDOM صحيح، والصنف موجود، والارتفاع مضبوط.
//  نفس درس زر النسخ في الدفعة السابقة — ما يُرى لا يُمسَك بفحص البنية وحده.
//
//  هذه الوحدة تُوحّد **الشكل**، وstyles.css يُعرّف **المظهر** الغائب.

const KINDS = {
  /** جدول: صفوف متساوية تحت ترويسة */
  table: n => line('sk-field sk-half') + rows(n || 6, 'sk-row'),
  /** قائمة: عناصر نصية متتابعة */
  list: n => rows(n || 4, 'sk-field'),
  /** بطاقات: كتل أكبر */
  cards: n => rows(n || 3, 'sk-card'),
  /** جانت أو رسم: كتلة واحدة كبيرة فوقها شريط زمني */
  chart: () => line('sk-field') + block('sk-chart'),
  /** لوحة جانبية: عنوان ثم حقول */
  panel: n => line('sk-line sk-half') + rows(n || 3, 'sk-field'),
  /** بطاقة مفردة: عنوان · شريط تقدّم · متن */
  card: () => line('sk-line sk-half') + line('sk-bar') + block('sk-field')
};

const div = cls => `<div class="skeleton ${cls}"></div>`;
const line = cls => div(cls + ' sk-gap');
const block = cls => div(cls);
const rows = (n, cls) => `<div class="sk-stack">${Array.from({ length: n }, () => div(cls)).join('')}</div>`;

/**
 * هيكل تحميل لنوع منطقة.
 * نوع غير معروف يرجع إلى `list` بدل أن يُنتج فراغًا — وهو العطل نفسه الذي
 * جاءت هذه الوحدة لتصلحه، فلا يجوز أن تعيد إنتاجه عند أول مفتاح مطبعيّ.
 */
export function skeleton(kind, n) {
  return (KINDS[kind] || KINDS.list)(n);
}

/** أنواع المناطق المعروفة — يقرؤها الاختبار كي لا تنحرف عن CSS. */
export const SKELETON_KINDS = Object.freeze(Object.keys(KINDS));
