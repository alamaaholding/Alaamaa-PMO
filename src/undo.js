// ═══════════════════════════════════════════════════════════════════════
//  undo.js — التراجع عن الإجراءات الهدّامة (وحدة ESM · الموجة W5)
// ═══════════════════════════════════════════════════════════════════════
//
//  AUDIT §ج-٢: نمط التراجع موجود وناضج في المنصّة — **وفي موضع واحد فقط**.
//  `handleDeleteTask` تلتقط لقطة كاملة للبند (حقوله · روابطه بالاتجاهين ·
//  متطلباته) ثم تعرض توستًا بزر تراجع يعيد بناءه كما كان. حلٌّ صحيح تمامًا،
//  ومطبَّق مرة واحدة من بين خمسة عشر إجراءً هدّامًا.
//
//  والبقية تقول للمستخدم «حُذف» ثم لا شيء. بل إن حوار حذف التعليق كان يقول
//  حرفيًا **«لا يمكن التراجع»** — وهو وعدٌ لم يكن ثمّة سبب تقنيّ لقطعه.
//
//  فهذه الوحدة تُخرج النمط من ذلك الموضع الواحد إلى واجهة واحدة، ليصير
//  التراجع **الافتراضَ لا الاستثناء** — وهو نفس المبدأ الذي طُبِّق في W4 على
//  حفظ موضع المستخدم: العلاج بنيوي لا موضعي.
//
//  ═══ لماذا لقطة قبل الحذف لا «حذف ناعم» ═══
//  الحذف الناعم (عمود deleted_at) يبدو أنظف، لكنه **تغيير مخطط قاعدة بيانات**
//  يمسّ كل استعلام وكل سياسة RLS في المنصّة — أي أنه ليس من جنس هذه الموجة.
//  واللقطة تُنجز نفس الوعد للمستخدم بلا أن تمسّ حرفًا في المخطط.
//
//  ═══ حدود صريحة ═══
//  ليس كل هدّام قابلًا للتراجع بأمانة، والادّعاء بغير ذلك أسوأ من الصمت:
//   • **مسح الخطة** له بالفعل شبكة أمان أنسب — لقطات الخطة
//     (`savePlanSnapshot`/`restorePlanSnapshot`)، وهي تحفظ الخطة كاملة لا
//     عنصرًا واحدًا. لا يُضاف إليها توست تراجع يوهم بأنه البديل.
//   • **حلّ الحزمة** يُعيد توزيع البنود على آباء جدد؛ عكسه إعادة بناء علاقات
//     لا مجرد صفّ، وأي تراجع ناقص فيه يترك الهرمية أسوأ مما كانت.

import { toast, toastUndo } from './toast.js';

/**
 * تنفيذ إجراء هدّام مع إتاحة التراجع عنه.
 *
 *   remove()   ينفّذ الحذف. أي خطأ منه يُرمى للمستدعي كما كان قبل هذا الغلاف.
 *   restore()  يعيد ما حُذف. أخطاؤه يلتقطها toastUndo ويُخبر بها المستخدم.
 *   refresh()  إعادة التحميل/التصيير — تُستدعى بعد الحذف وبعد التراجع معًا،
 *              فلا يبقى موضع واحد ينسى تحديث الشاشة بعد استعادة العنصر.
 *
 * الترتيب مقصود: التوست يظهر **بعد** نجاح الحذف وبعد تحديث الشاشة — فلا يُعرض
 * زرُّ تراجعٍ عن شيء لم يُحذف أصلًا.
 */
export async function undoable({ label, remove, restore, refresh, doneMsg }) {
  await remove();
  if (refresh) await refresh();
  toastUndo(label, async () => {
    await restore();
    if (refresh) await refresh();
    toast(doneMsg || 'استُعيد ما حُذف', 'ok');
  });
}
