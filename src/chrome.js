// ═══════════════════════════════════════════════════════════════════════
//  chrome.js — إظهار وإخفاء إطار الشاشة (وحدة ESM)
// ═══════════════════════════════════════════════════════════════════════
//
//  دالتان مجموعهما سطران، وكانتا في app/main.js — الملف الأكبر في طبقة
//  التطبيق. وهذا وحده كان يربط **تسعة ملفات** بـmain.js: كل شاشة تُفتح تخفي
//  إطار المشروع أولًا، فكل شاشة تستورد main.js فعليًا.
//
//  والنمط تكرّر في كل موجة W2: العُقد لا تأتي من الملفات الكبيرة، بل من
//  مساعدٍ صغيرٍ مدفونٍ فيها (`esc` · `todayISO` · `toast` · وهاتان). فصلُ
//  السطرين يفكّ ما لا يفكّه نقل الملف كله.
//
//  «الإطار» هنا: شريط العميل · صفّ المؤشّرات · التبويبات · شارة دورة الحياة ·
//  زرّ التقرير. كلها تخصّ شاشة المشروع وحدها، فتُخفى في كل شاشة سواها.

import { $ } from './config.js';

/**
 * إخفاء إطار شاشة المشروع — يُستدعى عند فتح أي شاشة أخرى (المحفظة، الحِمل،
 * العقود، الوصول…). يشمل شريط العميل، بخلاف showChrome.
 */
export function hideChrome() {
  $('#barClient').style.display = 'none';
  $('#kpisRow').style.display = 'none';
  $('#tabs').style.display = 'none';
  $('#lifeBadge').style.display = 'none';
  const e = $('#exportReport');
  if (e) e.style.display = 'none';
}

/**
 * إعادة إظهار الإطار عند العودة لشاشة المشروع.
 *
 * ولا تلمس `#barClient` — وهذا ليس سهوًا: مُناديها الوحيد (openProject) يُظهره
 * بنفسه قبل استدعائها، لأن ظهور شريط العميل مرتبط ببيانات العميل لا بالإطار.
 */
export function showChrome() {
  $('#kpisRow').style.display = '';
  $('#tabs').style.display = '';
  $('#lifeBadge').style.display = '';
  const e = $('#exportReport');
  if (e) e.style.display = '';
}
