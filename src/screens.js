//  screens.js — سجلّ الشاشات: ربطٌ متأخّر يكسر دورة التنقّل (الموجة W2)
// ═══════════════════════════════════════════════════════════════════════
//
//  المشكلة التي يحلّها، بالقياس لا بالانطباع: أربع عشرة نداءةَ تنقّل عابرة
//  للملفات بين سبعة ملفات، وهي **دورة حقيقية** لا مسألة ترتيب:
//
//      portfolio  ──renderClientHome──▶  clienthome
//          ▲                                 │
//          └──────── renderPortfolio ────────┘
//
//      و lifecycle · pgantt · session · contractsign  كلها تنادي شاشاتٍ
//      تنادي شاشاتٍ تناديها.
//
//  ولا ترتيبَ تحويلٍ يفكّها، لأن العقدة ليست في الترتيب: أيّ ملف يتحوّل أولًا
//  سيحتاج `import` من ملف لم يتحوّل بعد. (وESM نفسها تحتمل الدورات بين
//  تصريحات الدوال — لكن **الهجرة التدريجية** لا تحتملها: الوحدة المُحوَّلة لا
//  تستطيع استيراد اسم لا يزال يعيش في النطاق المشترك.)
//
//  فالحلّ ربطٌ متأخّر: الشاشة **تُسجّل نفسها**، والمُنادي يطلبها **بمفتاحها** لا
//  باسم دالتها. فلا ملف شاشةٍ يعرف ملف شاشةٍ أخرى، ولا حافة بينهما أصلًا.
//
//  والنمط ليس غريبًا على المشروع: `api.js` تفعل الشيء نفسه مع الوحدات الكسولة
//  (`window.dolOpen()` بعد `loadScript`) — «ربط متأخّر متعمَّد» بنصّ ترويستها.
//
//  ═══ ما لا تفعله هذه الوحدة، عمدًا ═══
//
//  لا تلمس `SCREEN`. كل دالة شاشة تضبطه بنفسها أول سطر فيها (تُحقّق ذلك
//  الاختبارات)، فطيُّه هنا تغييرُ سلوكٍ مدسوسٌ في تغيير بنية — وهو ما تمنعه
//  القاعدة الحاكمة الثانية. هذه الوحدة **إعادة توجيه ولا شيء غيرها**.

/** مفتاح الشاشة → دالة تصييرها. تُملأ عند تحميل الحزمة، وتُقرأ عند التنقّل. */
const registry = new Map();

/**
 * تسجيل شاشة. يُنادى مرة واحدة عند تحميل ملف الشاشة.
 *
 * التسجيل المكرَّر **خطأ يُرمى** لا تجاوزٌ صامت: مفتاحان بالاسم نفسه يعنيان أن
 * نصف نداءات التنقّل تذهب لشاشة والنصف الآخر لأخرى، بحسب ترتيب التحميل — وهو
 * أسوأ عطلٍ ممكن هنا لأنه يعتمد على البناء لا على الكود.
 */
export function registerScreen(key, render) {
  if (typeof key !== 'string' || !key) throw new Error('مفتاح شاشة غير صالح');
  if (typeof render !== 'function') throw new Error(`الشاشة "${key}" سُجّلت بغير دالة`);
  if (registry.has(key)) throw new Error(`الشاشة "${key}" مُسجَّلة مرتين`);
  registry.set(key, render);
  return render;   // تُعاد كما هي كي يبقى `export const x = registerScreen(...)` ممكنًا
}

/**
 * الانتقال إلى شاشة بمفتاحها. الوسائط تُمرَّر كما هي، والقيمة المُعادة كما هي —
 * فالشاشات غير المتزامنة تبقى قابلة للانتظار عند مُناديها تمامًا كما كانت.
 *
 * مفتاح غير مُسجَّل **خطأ يُرمى** لا `undefined` صامت: النداء الوحيد الذي يصل
 * إلى هنا بمفتاح مجهول هو خطأ مطبعيّ، وابتلاعه يُنتج زرًّا لا يفعل شيئًا بلا
 * أثر واحد في الطرفية.
 */
export function showScreen(key, ...args) {
  const render = registry.get(key);
  if (!render) {
    throw new Error(`شاشة غير مُسجَّلة: "${key}" (المُسجَّل: ${[...registry.keys()].join(', ') || 'لا شيء'})`);
  }
  return render(...args);
}

/** هل الشاشة مُسجَّلة؟ للفحص لا للتنقّل. */
export function hasScreen(key) { return registry.has(key); }

/** المفاتيح المُسجَّلة — يقرؤها الاختبار وحده. */
export function registeredScreens() { return [...registry.keys()]; }
