// ═══════════════════════════════════════════════════════════════════════
//  actions.js — سجلّ المعالِجات: يكسر آخر دورة في W2
// ═══════════════════════════════════════════════════════════════════════
//
//  بقيت بعد سجلّ الشاشات دورةٌ من أربعة ملفات (١٣٤ KB) تجب أن تُحوَّل معًا:
//
//      views ──▶ projectactions ──┐
//        ▲                        │  render
//        └────────────────────────┘
//      و taskpanel و lifecycle داخلها للسبب نفسه.
//
//  ومصدرها اتجاهٌ واحد: **views.js ينادي مُعالِجات غيره**. أمّا الاتجاه المقابل
//  (`render` من views) فهو اعتماد طبقةٍ على طبقة العرض — مشروع ولا يُكسَر.
//
//  فحين يكفّ views عن نداء غيره بالاسم، تنهار الدورة كلها: يصير `views` ورقةً
//  يعتمد عليها الجميع ولا يعتمد على أحد.
//
//  ═══ لماذا سجلّ لا استيراد ═══
//
//  الاثنتا عشرة حافة كلّها من شكلٍ واحد قِيس قبل التصميم:
//
//      b.onclick = () => handler(b.dataset.x)
//
//  أي **ربط مُعالِج بعنصر**، لا نداء منطق. والعنصر يحمل بياناته في `data-*`
//  أصلًا — وهو اصطلاح المشروع القائم (`data-tkopen` · `data-gotask` ·
//  `data-deps`). فالسجلّ يكمل ما هو قائم: العنصر يقول ماذا يريد، والطبقة التي
//  تملك المنطق تقول كيف يُنفَّذ.
//
//  وهو أخو `screens.js` حرفيًّا: ذاك ينقل **بين** الشاشات، وهذا ينفّذ **داخلها**.
//
//  ═══ ما لا يفعله ═══
//
//  لا يحلّ محلّ الاستيراد حين يكون الاستيراد ممكنًا. المعالِجات وحدها تُسجَّل —
//  ما تنتجه الوحدة من قيمٍ أو HTML يُستورَد كالمعتاد. الالتفاف على استيرادٍ
//  ممكن بسجلٍّ يُخفي التبعية ولا يزيلها.

/** مفتاح المعالِج → دالته. تُملأ عند تحميل الحزمة، وتُقرأ عند التفاعل. */
const registry = new Map();

/**
 * تسجيل مُعالِج. التسجيل المكرَّر **خطأ يُرمى** لا تجاوزٌ صامت: مفتاحان بالاسم
 * نفسه يعنيان أن نصف النقرات تذهب لمعالِج والنصف الآخر لآخر، بحسب ترتيب
 * التحميل — عطلٌ يعتمد على البناء لا على الكود.
 */
export function registerAction(key, handler) {
  if (typeof key !== 'string' || !key) throw new Error('مفتاح مُعالِج غير صالح');
  if (typeof handler !== 'function') throw new Error(`المُعالِج "${key}" سُجّل بغير دالة`);
  if (registry.has(key)) throw new Error(`المُعالِج "${key}" مُسجَّل مرتين`);
  registry.set(key, handler);
  return handler;
}

/**
 * تنفيذ مُعالِج بمفتاحه. الوسائط تُمرَّر كما هي والقيمة المُعادة كما هي، فيبقى
 * غير المتزامن قابلًا للانتظار عند مُناديه تمامًا كما كان.
 *
 * مفتاح غير مُسجَّل **خطأ يُرمى**: النداء الوحيد الذي يصل بمفتاح مجهول خطأ
 * مطبعيّ، وابتلاعه يُنتج زرًّا لا يفعل شيئًا بلا أثر واحد في الطرفية.
 */
export function runAction(key, ...args) {
  const handler = registry.get(key);
  if (!handler) {
    throw new Error(`مُعالِج غير مُسجَّل: "${key}" (المُسجَّل: ${[...registry.keys()].join(', ') || 'لا شيء'})`);
  }
  return handler(...args);
}

/** هل المُعالِج مُسجَّل؟ للفحص لا للتنفيذ. */
export function hasAction(key) { return registry.has(key); }

/** المفاتيح المُسجَّلة — يقرؤها الاختبار وحده. */
export function registeredActions() { return [...registry.keys()]; }
